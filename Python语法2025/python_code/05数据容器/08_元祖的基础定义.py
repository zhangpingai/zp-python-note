
"""
(元素1, ...,..., 元素N)
"""

# 字面量
(1, 3, 5, "haha")

# 变量
t1 = (1, 2, 3, "6")
print(t1, "类型：", type(t1))

# 得到空元组
t1 = ()
t2 = tuple()
print(type(t1), type(t2))

# 只有1个元素的元组（特殊写法）
t1 = (1,)       # 只有1个元素，也要写一个逗号
print(type(t1))

# 元组的嵌套
t1 = ( (1, 2, 3), (4, 5, 6) )
print(t1[1][1]) # 元祖也有下标，可以通过[下标]取值


